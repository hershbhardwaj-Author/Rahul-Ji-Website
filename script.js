  const modalVol = document.getElementById('modalBookVol');
  const modalTitle = document.getElementById('modalBookTitle');
  const modalSubtitle = document.getElementById('modalBookSubtitle');
  const modalExcerpt = document.getElementById('modalBookExcerpt');
  const modalCoverImg = document.getElementById('modalBookCoverImg');
  const modalPublisher = document.getElementById('modalBookPublisher');
  const modalChaptersList = document.getElementById('modalBookChapters');
  const modalAudience = document.getElementById('modalBookAudience');
  const modalNarrative = document.getElementById('modalBookNarrative');

  function openBookModal(bookId) {
    const data = bookData[bookId];
    if (!data || !modalOverlay) return;

    if (modalVol) modalVol.textContent = data.volume;
    if (modalTitle) modalTitle.textContent = data.title;
    if (modalSubtitle) modalSubtitle.textContent = data.subtitle;
    if (modalExcerpt) modalExcerpt.textContent = `“${data.excerpt}”`;
    if (modalAudience) modalAudience.textContent = data.idealFor;
    if (modalPublisher) modalPublisher.textContent = data.publisher;

    if (modalCoverImg) {
      modalCoverImg.src = data.cover;
      modalCoverImg.alt = data.title;
    }

    if (modalChaptersList) {
      modalChaptersList.innerHTML = '';
      data.chapters.forEach(ch => {
        const li = document.createElement('li');
        li.textContent = ch;
        modalChaptersList.appendChild(li);
      });
    }

    if (modalNarrative && data.narrative) {
      modalNarrative.innerHTML = '';
      data.narrative.forEach(pText => {
        const p = document.createElement('p');
        p.textContent = pText;
        p.style.marginBottom = '0.85rem';
        p.style.lineHeight = '1.75';
        modalNarrative.appendChild(p);
      });
    }

    modalOverlay.classList.add('active');
    document.body.style.overflow = 'hidden';
  }

  function closeBookModal() {
    if (!modalOverlay) return;
    modalOverlay.classList.remove('active');
    document.body.style.overflow = '';
  }

  // Bind click handlers to book preview buttons
  document.querySelectorAll('[data-book-id]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const id = btn.getAttribute('data-book-id');
      openBookModal(id);
    });
  });

  modalCloseBtn?.addEventListener('click', closeBookModal);
  
  modalOverlay?.addEventListener('click', (e) => {
    if (e.target === modalOverlay) {
      closeBookModal();
    }
  });

  window.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modalOverlay?.classList.contains('active')) {
      closeBookModal();
    }
  });

  // 5. Copy Email to Clipboard with UI Feedback
